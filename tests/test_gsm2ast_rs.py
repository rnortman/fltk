TREE_GRAMMAR = "tree := name:word , child:tree? , kids:tree* ;\nword := w:/[a-z]+/ ;\n"
"""A rule holding itself at every arity: the whole container matrix in one cycle."""

KEYED_TREE_GRAMMAR = "node := key:word , kid:node? , kids:node* ;\nword := w:/[a-z]+/ ;\n"
KEYED_TREE_SIDECAR = "rule word { transparent; }\nrule node { key: key; }\n"
"""``TREE_GRAMMAR`` with the repeated position keyed, so the recursive container is a map."""


def model_for(grammar_text: str, sidecar: str | None = None) -> am.AstModel:
    return fixtures.model_for(grammar_text, sidecar, ac.Backend.RUST)


def generate(grammar_text: str, sidecar: str | None = None, **kwargs: str) -> str:
    return gsm2ast_rs.generate_ast_rs(model_for(grammar_text, sidecar), **kwargs)


def block(src: str, header: str) -> str:
    """The emitted item starting with ``header``, through its own closing brace.

    The brace is the one at ``header``'s own indentation, so an item nested in a module can be
    read the same way a top-level one is.
    """
    start = src.index(header)
    closer = "\n" + " " * (len(header) - len(header.lstrip())) + "}"
    return src[start : src.index(closer + "\n", start) + len(closer)]


_SPAN_SIGNATURE = "    pub fn span(&self) -> &::fltk_cst_core::Span {"


def impl_blocks(src: str, type_name: str) -> list[str]:
    """Every ``impl <type_name> { ... }`` the module emits, in order.

    A type can get more than one — the span accessor and ``from_cst`` are separate blocks — so a
    question about one of them has to look at all of them.
    """
    header = f"impl {type_name} {{"
    blocks: list[str] = []
    start = src.find(header)
    while start != -1:
        end = src.index("\n}\n", start) + 2
        blocks.append(src[start:end])
        start = src.find(header, end)
    return blocks


def has_span_method(src: str, type_name: str) -> bool:
    """Whether the emitted module gives ``type_name`` the enum ``span()`` accessor.

    Keyed on the emitted signature, not on the doc comment above it: every use below is a
    negative assertion, which a reworded comment would satisfy while proving nothing.
    """
    return any(f"{_SPAN_SIGNATURE}\n" in body for body in impl_blocks(src, type_name))


