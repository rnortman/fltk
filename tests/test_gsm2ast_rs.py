            '            "expr",\n'
            "            cst_node.span(),\n"
            "            operands,\n"
            "            operators,\n"
            "            |operand| Self::Operand(Box::new(operand)),\n"
            "            |operator, lhs, rhs, span| {\n"
            "                Self::Binary(ExprBinary {\n"
            "                    op: operator,\n"
            "                    lhs: Box::new(lhs),\n"
            "                    rhs: Box::new(rhs),\n"
